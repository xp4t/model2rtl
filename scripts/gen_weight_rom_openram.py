#!/usr/bin/env python3
"""Stage 2, Backend B: build the SKY130 OpenRAM/OpenROM parameter macros.

    scripts/gen_weight_rom_openram.py

It consumes the SAME canonical parameter images as the portable backend
(src/model2rtl/param_image.py) -- there is exactly one packing implementation
in this project -- writes OpenROM input data files, invokes the ACTUAL
installed OpenROM compiler, verifies the produced files rather than trusting an
exit code, parses the DRC/LVS reports, and emits the fixed-interface wrapper

    rtl/mnist_mlp_params_openram.v

Nothing is claimed that was not produced.  Every macro's real outcome, including
the tool limitations that block a shape, is recorded in
build/openram/openram_build.json and reported verbatim.
"""

