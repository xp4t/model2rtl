_BBOX_RB = r'''
gds = ENV["GDS_IN"]
ly = RBA::Layout.new
ly.read(gds)
c = ly.top_cells[0]
b = c.dbbox
puts "BBOX_JSON {\"top_cell\": \"#{c.name}\", \"n_top_cells\": #{ly.top_cells.size}, \"cells\": #{ly.cells}, \"dbu\": #{ly.dbu}, \"left_um\": #{b.left}, \"bottom_um\": #{b.bottom}, \"right_um\": #{b.right}, \"top_um\": #{b.top}, \"width_um\": #{b.width}, \"height_um\": #{b.height}, \"area_um2\": #{b.width * b.height}}"
'''


def gds_bbox(gds_path: str, scratch: str) -> dict:
    """Measure the macro bounding box FROM THE GDS, hierarchy resolved.

    KLayout reads the real layout database; nothing is taken from a log line.
    """
    import json
    if not os.path.isfile(KLAYOUT):
        raise RuntimeError("klayout not found at %s" % KLAYOUT)
    os.makedirs(scratch, exist_ok=True)
    rb = os.path.join(scratch, "_bbox.rb")
    with open(rb, "w") as fh:
        fh.write(_BBOX_RB)
    env = dict(os.environ, GDS_IN=os.path.abspath(gds_path))
    p = subprocess.run([KLAYOUT, "-b", "-r", rb], capture_output=True,
                       text=True, env=env, timeout=1800)
    for line in (p.stdout + p.stderr).splitlines():
        if line.startswith("BBOX_JSON "):
            d = json.loads(line[len("BBOX_JSON "):])
            d["source"] = "GDS, measured with KLayout (hierarchy resolved)"
            d["gds_sha256"] = sha256_file(gds_path)
            return d
    raise RuntimeError("klayout produced no bbox for %s:\n%s"
                       % (gds_path, p.stdout + p.stderr))


_LEF_SIZE = re.compile(r"^\s*SIZE\s+([\d.]+)\s+BY\s+([\d.]+)\s*;", re.M)


def lef_size(lef_path: str) -> Optional[dict]:
    """The LEF abstract SIZE, recorded as a cross-check only.

    It is normally SMALLER than the GDS bounding box because the GDS also
    contains the supply ring and labels outside the abstract outline.
    """
    if not os.path.isfile(lef_path):
        return None
    m = _LEF_SIZE.search(open(lef_path).read())
    if not m:
        return None
    w, h = float(m.group(1)), float(m.group(2))
    return {"width_um": w, "height_um": h, "area_um2": w * h,
            "note": "LEF abstract outline; the GDS bounding box is the "
                    "reported area and is usually larger"}


# --------------------------------------------------------------------------
# The upstream OpenROM Verilog: observed properties, never used as our backend
# --------------------------------------------------------------------------

def inspect_generated_verilog(v_path: str) -> dict:
    text = open(v_path).read()
    return {
        "path": v_path,
        "bytes": len(text),
        "uses_readmemb": "$readmemb" in text,
        "uses_readmemh": "$readmemh" in text,
        "has_delays": bool(re.search(r"#\s*\d", text)),
        "has_negedge": "negedge" in text,
        "byte_oriented_interface": bool(re.search(r"\[\s*7\s*:\s*0\s*\]", text)),
        "module_names": re.findall(r"^\s*module\s+(\w+)", text, re.M),
        "port_lines": [l.strip() for l in text.splitlines()
                       if re.match(r"\s*(input|output|inout)\b", l)],
        "verdict": ("upstream artefact only: it is NOT used as the model2rtl "
                    "functional backend"),
    }
