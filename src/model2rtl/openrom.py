import os
import re
import subprocess
import time
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence, Tuple

OPENRAM_ROOT = "/home/rithwik/OpenRAM"
PDK_ROOT = "/home/rithwik/pdk"
KLAYOUT = os.path.expanduser("~/klayout_cf/klqt/klayout")

#: words_per_row is an INTERNAL physical folding choice.  It changes the array
#: aspect ratio only: never the logical depth, the word width or the bit
#: packing.  words_per_row = 1 is excluded because it crashes this OpenROM
#: revision (rom_address_control_array has no attribute local_insts).
DEFAULT_WPR_CANDIDATES = (4, 8, 2, 16)

VIEW_EXTS = ("gds", "sp", "lvs.sp", "lef", "v", "log", "py", "html")
REQUIRED_VIEWS = ("gds", "sp", "lvs.sp", "lef", "v")


def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def openram_env() -> dict:
    env = dict(os.environ)
    env.update({
        "OPENRAM_ROOT": OPENRAM_ROOT,
        "OPENRAM_HOME": os.path.join(OPENRAM_ROOT, "compiler"),
        "OPENRAM_TECH": os.path.join(OPENRAM_ROOT, "technology"),
        "PDK_ROOT": PDK_ROOT,
        "PDKPATH": os.path.join(PDK_ROOT, "sky130A"),
        "PYTHONPATH": os.path.join(OPENRAM_ROOT, "compiler"),
        "PATH": "/home/rithwik/netgen-install/bin:"
                "/home/rithwik/klayout_cf/magic/bin:"
                + os.environ.get("PATH", ""),
    })
    return env


def toolchain_versions() -> dict:
    def git(*args):
        try:
            return subprocess.run(["git", "-C", OPENRAM_ROOT] + list(args),
                                  capture_output=True, text=True,
                                  timeout=60).stdout.strip()
        except Exception as exc:                       # pragma: no cover
            return "unavailable: %s" % exc

    def ver(cmd):
        try:
            p = subprocess.run(cmd, capture_output=True, text=True, timeout=60,
                               env=openram_env())
            return (p.stdout + p.stderr).strip().splitlines()[0]
        except Exception as exc:
            return "unavailable: %s" % exc

    return {
        "openram_root": OPENRAM_ROOT,
        "openram_commit": git("rev-parse", "HEAD"),
        "openram_branch": git("rev-parse", "--abbrev-ref", "HEAD"),
        "openram_describe": git("log", "-1", "--format=%H %cI"),
        # Distinguish a modified OpenRAM SOURCE tree (which Stage 5 forbids)
        # from untracked PDK-derived cell libraries the installer creates.
        "openram_tracked_files_modified": bool(
            [l for l in git("status", "--porcelain").splitlines()
             if not l.startswith("??")]),
        "openram_untracked_paths": [l[3:] for l in
                                    git("status", "--porcelain").splitlines()
                                    if l.startswith("??")],
        "pdk_root": PDK_ROOT,
        "pdk_sky130A_present": os.path.isdir(os.path.join(PDK_ROOT, "sky130A")),
        "magic": ver(["magic", "--version"]),
        "netgen": ver(["netgen", "-batch", "quit"]),
        "klayout": ver([KLAYOUT, "-v"]),
    }


