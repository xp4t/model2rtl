"""Stage 5: a reusable driver for the installed OpenROM compiler.

Nothing here trusts an exit code.  Every run is judged by the artefacts it
actually produced, every macro's bit content is re-derived independently from
the generated SPICE netlist, and every measured area comes from the generated
GDS rather than from a log line.

The installed toolchain is used exactly as it is: OpenRAM stable at commit
b2b069ce119d1488cbe6883b2240bceb5c7ce29a with PDK_ROOT=/home/rithwik/pdk.
Stage 5 does not update, patch or fork it.
"""

from __future__ import annotations

