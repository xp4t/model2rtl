def write_config(name: str, word_size_bytes: int, wpr: int, data_path: str,
                 outdir: str, check_lvsdrc: bool) -> str:
    cfg_path = os.path.join(outdir, name + "_cfg.py")
    out_path = os.path.join(outdir, "out")
    os.makedirs(out_path, exist_ok=True)
    with open(cfg_path, "w") as fh:
        fh.write("""# GENERATED by model2rtl Stage 5 (src/model2rtl/openrom.py).
# words_per_row is an internal physical folding choice only: the logical depth,
# the word width and the bit packing are unchanged by it.
word_size = %d
words_per_row = %d
check_lvsdrc = %s
use_nix = False
rom_data = "%s"
data_type = "hex"
output_name = "%s"
output_path = "%s/"
tech_name = "sky130"
nominal_corner_only = True
route_supplies = "ring"
""" % (word_size_bytes, wpr, check_lvsdrc, data_path, name, out_path))
    return cfg_path


def _run(cfg_path: str, cwd: str, timeout: int) -> Tuple[int, str, float]:
    cmd = [os.path.join(OPENRAM_ROOT, ".venv", "bin", "python"),
           os.path.join(OPENRAM_ROOT, "rom_compiler.py"), "-d", cfg_path]
    t0 = time.time()
    try:
        # stdin MUST be closed: OpenRAM drops into pdb on an internal error and
        # would otherwise wait for input forever.
        p = subprocess.run(cmd, cwd=cwd, env=openram_env(),
                           stdin=subprocess.DEVNULL, capture_output=True,
                           text=True, timeout=timeout)
        return p.returncode, p.stdout + p.stderr, time.time() - t0
    except subprocess.TimeoutExpired as exc:
        return -1, "TIMEOUT after %d s\n%s" % (timeout, exc.stdout or ""), \
            time.time() - t0


def error_signature(log_text: str) -> dict:
    """The real failure, not the pdb noise OpenRAM prints afterwards."""
    lines = log_text.splitlines()
    frames = [l.strip() for l in lines
              if l.strip().startswith('File "/home/rithwik/OpenRAM')]
    errs = [l for l in lines if l.startswith("ERROR")]
    exc = [l.strip() for l in lines
           if re.match(r"^\w*(Error|Exception)\b", l.strip())
           and "BdbQuit" not in l]
    return {
        "openram_error_lines": errs[-3:],
        "last_openram_frame": frames[-1] if frames else None,
        "exception": exc[-1] if exc else None,
        "note": "OpenRAM enters pdb on internal errors, so the log tail is "
                "always BdbQuit; the frame above is the real failure point.",
    }


def parse_physical_verification(log_text: str, name: str) -> dict:
    drc = None
    m = re.search(r"DRC Errors\s+%s\s+(\d+)" % re.escape(name), log_text)
    if m:
        drc = int(m.group(1))
    elif re.search(r"DRC.*%s.*(passed|clean)" % re.escape(name), log_text, re.I):
        drc = 0
    lvs = "not run"
    if re.search(r"%s\s+LVS mismatch" % re.escape(name), log_text):
        lvs = "MISMATCH"
    elif re.search(r"LVS\s+Errors\s+%s\s+0" % re.escape(name), log_text):
        lvs = "clean"
    elif re.search(r"LVS.*(passed|clean)", log_text, re.I):
        lvs = "clean"
    return {
        "drc_errors": drc,
        "drc_status": ("clean" if drc == 0 else ("%d errors" % drc)
                       if drc is not None else "not run / not reported"),
        "lvs_status": lvs,
    }


def collect_views(outdir: str, name: str, root: str) -> Dict[str, dict]:
    od = os.path.join(outdir, "out")
    views = {}
    for ext in VIEW_EXTS:
        p = os.path.join(od, "%s.%s" % (name, ext))
        if os.path.exists(p) and os.path.getsize(p) > 0:
            views[ext] = {"path": os.path.relpath(p, root),
                          "bytes": os.path.getsize(p),
                          "sha256": sha256_file(p)}
    # anything else the tool emitted that we did not anticipate
    if os.path.isdir(od):
        for f in sorted(os.listdir(od)):
            ext = f[len(name) + 1:] if f.startswith(name + ".") else None
            if ext and ext not in views and ext not in VIEW_EXTS:
                p = os.path.join(od, f)
                views[ext] = {"path": os.path.relpath(p, root),
                              "bytes": os.path.getsize(p),
                              "sha256": sha256_file(p),
                              "unanticipated": True}
    return views


@dataclass
class RomBuild:
    name: str
    depth: int
    width: int
    outdir: str
    attempts: List[dict] = field(default_factory=list)
    words_per_row: Optional[int] = None
    returncode: Optional[int] = None
    elapsed: float = 0.0
    views: Dict[str, dict] = field(default_factory=dict)
    generated: bool = False
    data: dict = field(default_factory=dict)
    physical_verification: dict = field(default_factory=dict)
    error: dict = field(default_factory=dict)


def build_rom(name: str, depth: int, width_bits: int, hex_stream: str,
              outdir: str, root: str,
              wpr_candidates: Sequence[int] = DEFAULT_WPR_CANDIDATES,
              check_lvsdrc: bool = False, timeout: int = 10800) -> RomBuild:
    """Generate one OpenROM macro, trying documented words_per_row values.

    Every attempt -- including every failure, with its traceback frame and the
    resulting array geometry -- is recorded.  Nothing is retried silently.
    """
    if width_bits % 8:
        raise ValueError("%s: %d-bit word is not byte granular; OpenROM's "
                         "word_size is expressed in bytes" % (name, width_bits))
    os.makedirs(outdir, exist_ok=True)
    b = RomBuild(name=name, depth=depth, width=width_bits, outdir=outdir)

    data_path = os.path.join(outdir, name + ".hex")
    with open(data_path, "w") as fh:
        fh.write(hex_stream)
    read_back = open(data_path).read().strip()
    if read_back != hex_stream.strip():
        raise RuntimeError("%s: ROM data file did not round trip" % name)
    b.data = {
        "path": os.path.relpath(data_path, root),
        "sha256": sha256_file(data_path),
        "hex_digits": len(hex_stream.strip()),
        "bits": len(hex_stream.strip()) * 4,
    }

    for wpr in wpr_candidates:
        cfg = write_config(name, width_bits // 8, wpr, data_path, outdir,
                           check_lvsdrc)
        rc, log, elapsed = _run(cfg, outdir, timeout)
        logpath = os.path.join(outdir, "%s_wpr%d.log" % (name, wpr))
        with open(logpath, "w") as fh:
            fh.write(log)
        views = collect_views(outdir, name, root)
        missing = [v for v in REQUIRED_VIEWS if v not in views]
        ok = (rc == 0 and not missing)
        attempt = {
            "words_per_row": wpr,
            "array_rows": -(-depth // wpr),
            "array_cols": width_bits * wpr,
            "returncode": rc,
            "elapsed_seconds": round(elapsed, 1),
            "log": os.path.relpath(logpath, root),
            "views_generated": sorted(views),
            "missing_required_views": missing,
            "generated": ok,
        }
        if not ok:
            attempt["error_signature"] = error_signature(log)
        b.attempts.append(attempt)
        if ok:
            b.words_per_row = wpr
            b.returncode = rc
            b.elapsed = elapsed
            b.views = views
            b.generated = True
            b.physical_verification = parse_physical_verification(log, name)
            b.physical_verification["checked_during_generation"] = check_lvsdrc
            return b
        # clean the output dir so a later attempt cannot inherit stale views
        od = os.path.join(outdir, "out")
        for f in list(os.listdir(od)) if os.path.isdir(od) else []:
            if f.startswith(name + "."):
                os.remove(os.path.join(od, f))

    b.generated = False
    b.error = b.attempts[-1].get("error_signature", {}) if b.attempts else {}
    return b


# --------------------------------------------------------------------------
# Independent content verification, straight out of the generated SPICE
# --------------------------------------------------------------------------

#: Derived empirically in Stage 5 from the Stage-2 weights_l2 macro, whose
#: contents are known, and confirmed exactly on 1280/1280 bits:
#:
#:     row    = word_address // words_per_row
#:     subcol = word_address %  words_per_row
#:     col    = bit * words_per_row + subcol,  bit numbered MSB first
#:     cell   = one_cell  when  word_bit(width-1-bit) == 1
#:
#: One extra all-ones row is emitted below the data rows; it holds no data.
SPICE_BIT_MAP = ("row = addr // words_per_row; col = bit*words_per_row + "
                 "addr % words_per_row with bit numbered MSB first; "
                 "rom_base_one_cell = 1, rom_base_zero_cell = 0")

_BITCELL = re.compile(
    r"^Xbit_r(\d+)_c(\d+)\n(?:\+.*\n)*?\+\s*\S*rom_base_(one|zero)_cell\s*$",
    re.M)


def spice_bit_grid(sp_path: str, name: str) -> Dict[Tuple[int, int], int]:
    text = open(sp_path).read()
    m = re.search(r"^\.SUBCKT %s_rom_base_array.*?^\.ENDS"
                  % re.escape(name), text, re.S | re.M)
    if not m:
        raise RuntimeError("%s: no rom_base_array subcircuit in %s"
                           % (name, sp_path))
    grid = {}
    for r, c, kind in _BITCELL.findall(m.group(0)):
        grid[(int(r), int(c))] = 1 if kind == "one" else 0
    if not grid:
        raise RuntimeError("%s: no programmed bit cells found" % name)
    return grid


def verify_spice_content(sp_path: str, name: str, rows: Sequence[int],
                         width: int, words_per_row: int) -> dict:
    """Compare every programmed cell in the generated netlist against the
    physical image.  This is the proof that the GDS/SPICE macro was built from
    the same bits the logical model uses."""
    grid = spice_bit_grid(sp_path, name)
    depth = len(rows)
    n_rows = -(-depth // words_per_row)
    checked = mismatches = 0
    first_bad = []
    for a in range(depth):
        r, sub = a // words_per_row, a % words_per_row
        for bit in range(width):
            c = bit * words_per_row + sub
            want = (rows[a] >> (width - 1 - bit)) & 1
            got = grid.get((r, c))
            if got is None:
                raise RuntimeError("%s: netlist has no cell at r%d c%d"
                                   % (name, r, c))
            checked += 1
            if got != want:
                mismatches += 1
                if len(first_bad) < 5:
                    first_bad.append({"addr": a, "bit": bit, "row": r,
                                      "col": c, "expected": want, "found": got})
    extra = {k: v for k, v in grid.items() if k[0] >= n_rows}
    return {
        "spice": os.path.basename(sp_path),
        "bit_map": SPICE_BIT_MAP,
        "data_rows": n_rows,
        "cells_in_netlist": len(grid),
        "bits_checked": checked,
        "bit_mismatches": mismatches,
        "first_mismatches": first_bad,
        "non_data_cells": len(extra),
        "non_data_cells_all_ones": all(v == 1 for v in extra.values()),
        "exact": mismatches == 0,
    }


